(৪) কার্যনির্বাহী পরিষদ সদস্যবর্গের কার্যপরিধি:

- ০১. সভাপতি:  
    (১) সভাপতি অ্যাসোসিয়েশনের কার্যনির্বাহী পরিষদ এবং অ্যাসোসিয়েশনের সাংবিধানিক প্রধান।  
    (২) অ্যাসোসিয়েশনের সাধারণ সভা, কার্যনির্বাহী পরিষদের সভা ও অন্যান্য সভায়/আনুষ্ঠানিকতায় তিনি সভাপতিত্ব করবেন। অ্যাসোসিয়েশনের স্বার্থে পত্র-পত্রিকায়, সংবাদপত্রে কিংবা মিডিয়ায় এককভাবে কিংবা সাধারণ সম্পাদকের সাথে যৌথভাবে বিবৃতি/সাক্ষাৎকার প্রদান করবেন।  
    (৩) তিনি সাধারণ সম্পাদককে কার্যনির্বাহী পরিষদ সভা আহ্বান করতে অনুরোধ করবেন। সাধারণ সম্পাদক কোনো কারণে বা ইচ্ছাকৃতভাবে সভা আহ্বান না করলে সভাপতি নিজেই সভা আহ্বান করতে পারবেন কিংবা যুগ্ম সম্পাদকগণকে দিয়ে সভা আহ্বান করতে পারবেন।  
    (৪) তিনি অ্যাসোসিয়েশনের সকল প্রকল্প/ কর্মসূচি, কর্মচারী নিয়োগ/ বরখাস্তের সুপারিশ এবং সভাসমূহের প্রস্তাব/ সিদ্ধান্ত অনুমোদন করবেন।  
    (৫) কোন সভায় প্রস্তাব/ সিদ্ধান্ত গ্রহণে মতানৈক্য দেখা দিলে তিনি প্রকাশ্য ভোটের মাধ্যমে সংখ্যাগরিষ্ঠের মতানুযায়ী নিষ্পত্তি করবেন, পক্ষে-বিপক্ষে ভোট সমান সংখ্যক হলে সভাপতি উক্ত বিষয়ে সিদ্ধান্ত প্রদান করবেন।  
    (৬) গঠনতন্ত্রের যে কোন ধারা-উপধারা ব্যাখ্যা করে রুলিং প্রদান এবং বিশেষ প্রয়োজনে গঠনতন্ত্রের যে কোন ধারার কার্যকারিতা সাময়িকভাবে স্থগিত করনের পরামর্শ দিবেন।  
    (৭) তিনি অ্যাসোসিয়েশনের যে কোন প্রকল্প/কার্যক্রমের বাস্তবায়ন অগ্রগতি, অ্যাসোসিয়েশনের তহবিলের হিসাব পরীক্ষা এবং কার্যনির্বাহী পরিষদ সদস্য কিংবা অ্যাসোসিয়েশনের কর্মচারীদের কাজ পর্যবেক্ষণ করতে পারবেন।  
    (৮) কোষাধ্যক্ষের সাথে যৌথ স্বাক্ষরে অ্যাসোসিয়েশনের ব্যাংক হিসাব পরিচালনা করবেন।
    
- ০২. সহ-সভাপতি (২ জন):  
    (১) সভাপতির অনুপস্থিতিতে জ্যেষ্ঠতার ক্রমানুসারে সহ-সভাপতিগণ ভারপ্রাপ্ত সভাপতির দায়িত্ব পালন করবেন।  
    (২) কার্যনির্বাহী পরিষদ কর্তৃক গঠিত যে কোন উপ-পরিষদকে নেতৃত্ব দিবেন এবং কাজের অগ্রগতি তদারকি করবেন।  
    (৩) কার্যনির্বাহী পরিষদের সিদ্ধান্তক্রমে সহ-সভাপতিগণ অ্যাসোসিয়েশনের উপদেষ্টা পরিষদের সঙ্গে লিয়াজোঁ করবেন।  
    (৪) কার্যনির্বাহী পরিষদ কর্তৃক অর্পিত দায়িত্বসমূহ পালন করবেন।
    
- ০৩. সাধারণ সম্পাদক:  
    (১) সাধারণ সম্পাদক অ্যাসোসিয়েশনের প্রধান নির্বাহী। সংগঠনের মুখপাত্র হিসেবে বাকুর স্বার্থ সংশ্লিষ্ট বিষয়ে বিভিন্ন সরকারি/আধা-সরকারি প্রতিষ্ঠান, সমাজসেবা অধিদপ্তর, এনজিও এবং বিভিন্ন সমিতি/সংঘ/সংগঠনের সঙ্গে যোগাযোগ রাখবেন।  
    (২) সভাপতির অনুরোধক্রমে তিনি কার্যনির্বাহী পরিষদের সভা আহ্বান করবেন। অন্যান্য পরিষদের প্রধানকে সভা আহ্বানের অনুরোধ করবেন এবং নির্ধারিত বিষয়ের উপর রিপোর্ট সংগ্রহ করবেন।  
    (৩) তিনি অফিস ব্যবস্থাপনা সম্পাদকের সাথে যৌথভাবে সভার আলোচ্যসূচি প্রস্তুত, কার্যবিবরণী লিপিবদ্ধ, বিলি এবং সংরক্ষণ করবেন।  
    (৪) কার্যনির্বাহী পরিষদের অনুমোদিত প্রতিবেদন ও নিরীক্ষা রিপোর্ট সাধারণ সভায় পেশ করবেন এবং জবাবদিহি করবেন।  
    (৫) তিনি অ্যাসোসিয়েশনের দৈনন্দিন আয়-ব্যয় নিয়ন্ত্রণ করবেন। সভাপতির সঙ্গে আলোচনাক্রমে সাধারণ সম্পাদক সর্বোচ্চ ১০,০০০/- (দশ হাজার) টাকা পর্যন্ত নগদ খরচ করতে পারবেন অথবা অনুমোদন দিতে পারবেন। কোষাধ্যক্ষের সাথে যৌথভাবে অ্যাসোসিয়েশনের ব্যাংক হিসাব পরিচালনা করবেন এবং বার্ষিক বাজেট কার্যনির্বাহী পরিষদে পেশ করবেন।  
    (৬) সভাপতির অনুমোদনক্রমে তিনি অ্যাসোসিয়েশনের কর্মচারী নিয়োগ/অব্যাহতি, বেতন-ভাতা প্রদান/হ্রাস-বৃদ্ধি ও ছুটি মঞ্জুর করবেন।  
    (৭) তিনি কার্যনির্বাহী পরিষদ কর্তৃক অনুমোদিত চুক্তিতে স্বাক্ষর করবেন, প্রকল্প/কর্মসূচি/কার্যক্রম পরিচালনা/তদারকি করবেন এবং অ্যাসোসিয়েশনের যাবতীয় স্থাবর ও অস্থাবর বিষয়-সম্পত্তি, কাগজপত্র, দলিল-দস্তাবেজ ও হিসাব-নিকাশ রক্ষণাবেক্ষণের সার্বিক দায়িত্বে থাকবেন।  
    (৮) তিনি বিভাগীয় সম্পাদকদের নিয়ে সভা করবেন এবং সম্পাদকগণের কার্যাবলীর অগ্রগতি পর্যালোচনাপূর্বক সিদ্ধান্ত গ্রহণ করবেন, দাপ্তরিক কার্যাবলী সম্পর্কে দিক-নির্দেশনা দিবেন।  
    (৯) সাধারণ সম্পাদক নব-নির্বাচিত কার্যনির্বাহী পরিষদের নিকট নতুন পরিষদ ঘোষণার ১০ (দশ) দিনের মধ্যে অ্যাসোসিয়েশনের কার্যভার বুঝিয়ে দিতে বাধ্য থাকবেন।  
    (১০) সকল কাজের জন্য তিনি কার্যনির্বাহী পরিষদের নিকট জবাবদিহি করতে বাধ্য থাকবেন।  
    (১১) দায়িত্ব হতে পদত্যাগ করতে চাইলে তিনি সভাপতির নিকট পদত্যাগ পত্র পেশ করবেন এবং তা কার্যনির্বাহী পরিষদে গৃহীত না হওয়া পর্যন্ত দায়িত্ব পালন করতে থাকবেন।  
    (১২) কার্যনির্বাহী পরিষদ কর্তৃক অর্পিত দায়িত্বসমূহ পালন করবেন।
    
- ০৪. যুগ্ম সাধারণ সম্পাদক (১ জন):  
    (১) যুগ্ম সাধারণ সম্পাদক সাধারণ সম্পাদকের সকল কাজে সহযোগিতা করবেন।  
    (২) সভাপতির অনুরোধক্রমে অ্যাসোসিয়েশনের যে কোন দায়িত্ব পালন করবেন।  
    (৩) কার্যনির্বাহী পরিষদের মেয়াদ পূর্ণ হবার আগেই সাধারণ সম্পাদক দায়িত্ব পালনে অপারগ হলে বা তিনি পদত্যাগ করলে বা যে কোন কারণে সাধারণ সম্পাদক এর পদ শূন্য হলে যুগ্ম সাধারণ সম্পাদক জ্যেষ্ঠতার ক্রমানুসারে পরবর্তী নির্বাচন না হওয়া পর্যন্ত ভারপ্রাপ্ত সাধারণ সম্পাদক হিসেবে দায়িত্ব পালন করবেন।  
    (৪) ছুটি/অনুপস্থিতি/অসুস্থতা বা কোন কারণে সাধারণ সম্পাদক দায়িত্ব পালনে সাময়িকভাবে অসমর্থ হলে সাধারণ সম্পাদক পুনরায় কার্যভার গ্রহণ না করা পর্যন্ত যুগ্ম সম্পাদক জ্যেষ্ঠতার ক্রমানুসারে ভারপ্রাপ্ত সাধারণ সম্পাদক হিসেবে দায়িত্ব পালন করবেন।  
    (৫) অ্যাসোসিয়েশনের সার্বিক বিষয়ে সভাপতি ও সাধারণ সম্পাদকের সাথে যুক্ত থাকবেন এবং অ্যাসোসিয়েশনের সকল কর্মসূচি বাস্তবায়নে কার্যকরী ভূমিকা রাখবেন।  
    (৬) কার্যনির্বাহী পরিষদ কর্তৃক অর্পিত দায়িত্বসমূহ পালন করবেন।
    
- ০৫. সাংগঠনিক সম্পাদক (১ জন):  
    (১) সাংগঠনিক সম্পাদক অ্যাসোসিয়েশনের সাংগঠনিক কার্যক্রমের সাথে সম্পৃক্ত থাকবেন।  
    (২) সভাপতি ও সাধারণ সম্পাদকের সাথে যোগাযোগ রাখবেন এবং অ্যাসোসিয়েশনকে শক্তিশালী করার জন্য যথোপযুক্ত পদক্ষেপ গ্রহণ করবেন।  
    (৩) অ্যাসোসিয়েশনে নতুন সদস্য অন্তর্ভুক্ত করা তাঁদের প্রধানতম দায়িত্ব। কোন অবাঞ্ছিত কিংবা অনুপযুক্ত ব্যক্তি যাতে অ্যাসোসিয়েশনে সম্পৃক্ত না হয় সেদিকে লক্ষ্য রাখবেন।  
    (৪) কার্যনির্বাহী পরিষদ সভায়/সাধারণ সভায় সাংগঠনিক সুপারিশ/রিপোর্ট পেশ করবেন।  
    (৫) অ্যাসোসিয়েশনের কোন শাখা প্রতিষ্ঠা করার প্রয়োজন দেখা দিলে সে প্রস্তাব কার্যনির্বাহী পরিষদে অনুমোদনের জন্য পেশ করবেন।  
    (৬) কার্যনির্বাহী পরিষদ কর্তৃক অর্পিত অন্যান্য দায়িত্বসমূহ পালন করবেন।
    
- ০৬. কোষাধ্যক্ষ:  
    (১) কোষাধ্যক্ষ অ্যাসোসিয়েশনের সকল আর্থিক লেন-দেনের মুখ্য অধীক্ষকের দায়িত্ব পালন করবেন। অ্যাসোসিয়েশনের নামে সংগৃহীত সমুদয় অর্থ অ্যাসোসিয়েশনের নামে করা ব্যাংক হিসাবে জমা রাখবেন।  
    (২) অ্যাসোসিয়েশনের আর্থিক বিষয়াদি সম্পর্কে সভাপতি ও সাধারণ সম্পাদককে সম্যক জ্ঞাত রাখা, আয়-ব্যয়ের হিসেব সংরক্ষণ, কার্যনির্বাহী পরিষদ সভায় সমিতির আর্থিক ব্যবস্থাপনার উপর রিপোর্ট দেয়া তাঁর দায়িত্ব।  
    (৩) সভাপতি/সাধারণ সম্পাদক কর্তৃক পাশকৃত বিল, ভাউচার এর অর্থ পরিশোধ করবেন। পরিশোধিত বিল/ভাউচার, রশিদ/জমা/চেক বই, যাবতীয় হিসাব, কাগজ-পত্র ইত্যাদি সংরক্ষণ করবেন।  
    (৪) তিনি অ্যাসোসিয়েশনের বাজেট, আয়-ব্যয়, সঞ্চয় ও স্থিতির প্রতিবেদন প্রণয়ন করবেন এবং তা অনুমোদনের জন্য কার্যনির্বাহী পরিষদে পেশ করবেন।  
    (৫) তিনি অ্যাসোসিয়েশনের দৈনন্দিন ব্যয় নির্বাহের জন্য ১০,০০০/- (দশ হাজার) টাকা পর্যন্ত নিজ হাতে নগদ রাখতে পারবেন।  
    (৬) কার্যনির্বাহী পরিষদ বাতিল হলেও তিনি দায়িত্বভার পরবর্তী কার্যনির্বাহী পরিষদের কোষাধ্যক্ষ এর নিকট অর্পণের পূর্ব পর্যন্ত স্ব পদে বহাল থাকবেন।  
    (৭) কার্যনির্বাহী পরিষদ কর্তৃক অর্পিত দায়িত্বসমূহ পালন করবেন।
    
- ০৭. দপ্তর সম্পাদকঃ  
    (১) দপ্তর সম্পাদক প্রতিষ্ঠানের প্রশাসনিক ও দাপ্তরিক কার্যক্রম পরিচালনা করবেন। তিনি চিঠিপত্র আদান-প্রদান, সভা আহ্বান, রেকর্ড সংরক্ষণ এবং অফিসের জিনিসপত্র দেখাশোনা করবেন।  
    (২) সংগঠনের আসা ও পাঠানো সব চিঠিপত্র এবং ইমেইল ঠিকমতো নথিবদ্ধ ও বিতরণ করা, সব সদস্যের তালিকা, সভার কার্যবিবরণী (মিনিটস) এবং গুরুত্বপূর্ণ নথিপত্র সুশৃঙ্খলভাবে লিপিবদ্ধ করবেন।  
    (৩) সাধারণ সম্পাদকের সাথে আলোচনা করে সভার তারিখ ঠিক করা এবং নোটিশ সবার কাছে পাঠানো এবং অ্যালামনাইদের সাথে নিয়মিত যোগাযোগ রাখা এবং কেন্দ্রীয় সিদ্ধান্তগুলো পৌঁছে দেওয়া দায়িত্ব সুষ্ঠুভাবে পালন করবেন। 
    
- ০৮. মিডিয়া ও প্রচার বিষয়ক সম্পাদকঃ  
    (১) মিডিয়া ও প্রচার বিষয়ক সম্পাদক অ্যাসোসিয়েশনের প্রচার-প্রচারণা ও যোগাযোগের দায়িত্বে থাকবেন।  
    (২) তিনি বিবৃতি, লিফলেট, পোস্টার, বিজ্ঞপ্তি প্রভৃতির মাধ্যমে অ্যাসোসিয়েশনকে সংশ্লিষ্ট পেশাজীবী সমাজে ও বিভিন্ন সামাজিক সংগঠনের নিকট যথাযথভাবে উপস্থাপনের পদক্ষেপ নিবেন।  
    (৩) অ্যাসোসিয়েশনের আদর্শ, উদ্দেশ্য, প্রকল্প, কর্মসূচি প্রভৃতি বিষয়ে অ্যাসোসিয়েশনের সদস্য, পরিষদ এবং সমধর্মী সংগঠনসমূহের নিকট তুলে ধরবেন।  
    (৪) কার্যনির্বাহী পরিষদ কর্তৃক অর্পিত দায়িত্বসমূহ পালন করবেন।
    
- ০৯. সাহিত্য, গবেষণা ও প্রকাশনা সম্পাদকঃ  
    (১) সাহিত্য ও প্রকাশনা সম্পাদক অ্যাসোসিয়েশনের পত্রিকা, জার্নাল, সাময়িকী, ডাইরেক্টরি ইত্যাদি প্রকাশনা, সংকলন ও মুদ্রণের দায়িত্ব পালন করবেন।  
    (২) অ্যাসোসিয়েশন কর্তৃক প্রকাশিত পত্রিকা, জার্নাল, সাময়িকী, ডাইরেক্টরি ইত্যাদি বিলি-বণ্টন সংরক্ষণ ও রক্ষণাবেক্ষণ করবেন।  
    (৩) তিনি অ্যাসোসিয়েশনের বিভিন্ন প্রকাশনার জন্য লেখা, বিজ্ঞাপন, বিশিষ্ট ব্যক্তিবর্গের বাণী/বক্তব্য ইত্যাদি সংগ্রহপূর্বক সম্পাদনা করবেন।  
    (৪) কার্যনির্বাহী পরিষদ কর্তৃক অর্পিত দায়িত্বসমূহ পালন করবেন।
    
- ১০. শিক্ষার্থী কল্যাণ বিষয়ক সম্পাদকঃ  
    (১) বাংলা ডিসিপ্লিন-এ অধ্যয়নরত ছাত্রছাত্রীদের সঙ্গে বাকুর সংশ্লিষ্ট বিষয়ে যোগাযোগ রাখবেন।  
    (২)  বাংলা ডিসিপ্লিন-এর ছাত্রছাত্রীদের বৃত্তি প্রদানের সম্ভাবনা যাচাই, তহবিল গঠন এবং বৃত্তি প্রদানের উদ্যোগ নিবেন।  
    (৩) শিক্ষা বিষয়ক সম্মেলন/সেমিনার/কর্মশালা/স্টাডি ট্যুর এর আয়োজনের সম্ভাবনা যাচাই ও বাস্তবায়নের উদ্যোগ নিবেন।  
    (৪) কার্যনির্বাহী পরিষদ কর্তৃক অর্পিত দায়িত্বসমূহ সম্পাদন করবেন।
    
- ১১. সাংস্কৃতিক বিষয়ক সম্পাদকঃ  
    (১) সাংস্কৃতিক বিষয়ক সম্পাদক বাকুর সাংস্কৃতিক কার্যক্রম পরিচালনার মূল দায়িত্ব পালন করবেন এবং বিভিন্ন উৎসব, জাতীয় দিবস, এবং বিনোদনমূলক অনুষ্ঠান পরিকল্পনা ও বাস্তবায়ন করবেন।  
    (২) পুনর্মিলনী বা বিশেষ দিবসে সাংস্কৃতিক অনুষ্ঠানের রূপরেখা তৈরি করা, প্রাক্তন শিক্ষার্থী বা আমন্ত্রিত শিল্পীদের নিয়ে পরিবেশনা ঠিক করা, সাংস্কৃতিক কাজের জন্য খরচের হিসাব তৈরি করে কমিটির অনুমোদন নেওয়ার দায়িত্ব যথাযথভাবে পালন করবেন।  
    (৩) মঞ্চ সাজসজ্জা, শব্দ নিয়ন্ত্রণ এবং মহড়ার দলগুলোর সাথে কাজ করা এবং অনুষ্ঠান সুষ্ঠুভাবে পরিচালনা করার দায়িত্ব পালন করবেন।
    
- ১২. ক্রীড়া বিষয়ক সম্পাদকঃ  
    (১) ক্রীড়া ও সাংস্কৃতিক সম্পাদক অ্যাসোসিয়েশনের ক্রীড়া ও সাংস্কৃতিক বিষয়াদির দায়িত্বে থাকবেন।  
    (২) সদস্যদের নিয়ে খেলাধুলা, নাটক, সঙ্গীতানুষ্ঠান, আবৃত্তি প্রভৃতির আয়োজন করবেন।  
    (৩) দেশ-বিদেশের ঐতিহাসিক, স্বাস্থ্যকর ও দর্শনীয় স্থান পরিদর্শনের উদ্যোগ নিবেন।  
    (৪) কার্যনির্বাহী পরিষদ কর্তৃক অর্পিত দায়িত্বসমূহ পালন করবেন।
    
- ১৩. আন্তর্জাতিক যোগাযোগ, প্রচার ও সংযোগ বিষয়ক সম্পাদকঃ  
    (১) দেশের বাইরে থাকা প্রাক্তন শিক্ষার্থীদের সাথে সম্পর্ক উন্নয়ন, সংগঠনের কার্যক্রম বিশ্বব্যাপী প্রচার এবং নেটওয়ার্ক গড়ে তোলার মূল দায়িত্ব পালন করবেন। তিনি বিভিন্ন দেশের অ্যালামনাইদের এক প্ল্যাটফর্মে আনতে এবং সংগঠনের ভাবমূর্তি বাড়াতে কাজ করবেন।  
    (২) বিদেশে বসবাসকারী প্রাক্তন শিক্ষার্থীদের তথ্য সংগ্রহ ও তালিকা তৈরি করা, তাদের সাথে নিয়মিত যোগাযোগ রক্ষা করা এবং আন্তর্জাতিক শাখা বা চ্যাপ্টার (Chapter) গঠনে সহায়তা করবেন।  
    (৩) তিনি প্রবাসী অ্যালামনাইদের নিয়ে আন্তর্জাতিক সেমিনার, ওয়েবিনার বা ভার্চুয়াল সভার আয়োজন করবেন এবং বিশ্বজুড়ে ছড়িয়ে থাকা অ্যালামনাইদের মধ্যে পেশাগত ও সামাজিক সেতু বন্ধন তৈরি করা। 
    
- ১৪. নির্বাহী সদস্য - ১০ (দশ) জন:  
    (১) নির্বাহী সদস্যগণ অ্যালামনাই অ্যাসোসিয়েশন-এর কার্যনির্বাহী পরিষদের অন্যান্য সদস্য/পদধারীদের সমক্ষমতায় অ্যাসোসিয়েশনের কর্মকাণ্ডে অংশগ্রহণ করবেন এবং সঠিক সিদ্ধান্ত গ্রহণে ভূমিকা রাখবেন।  
    (২) যে কোন উপ-পরিষদের আহ্বায়কসহ অন্যান্য সদস্য হিসেবে দায়িত্ব পালন করবেন।  
    (৩) যে কোন সভায় সভাপতি এবং সহ-সভাপতিগণের অনুপস্থিতিতে নির্বাহী সদস্যগণ জ্যেষ্ঠতার ক্রমানুসারে সভাপতিত্ব করবেন।  
    (৪) সদ্য বিগত কার্যনির্বাহী পরিষদের সাধারণ সম্পাদক পদাধিকারবলে পরবর্তী পরিষদের কার্যনির্বাহী সদস্য হবেন এবং তিনি ১০ জন সদস্যের মধ্যে ক্রম তালিকায় ১ নম্বর হিসেবে গণ্য হবেন।  
    (৫) অ্যালামনাই অ্যাসোসিয়েশনের সকল বিষয়ে তীক্ষ্ণ দৃষ্টি রাখবেন এবং প্রয়োজনে অ্যাসোসিয়েশনের স্বার্থ সংশ্লিষ্ট বিষয়গুলো সভাপতির নজরে আনবেন।  
    (৬) কার্যনির্বাহী পরিষদ কর্তৃক সময়ে সময়ে অর্পিত দায়িত্বসমূহ পালন করবেন।
    

৩.৩ উপদেষ্টা পরিষদ:

অ্যাসোসিয়েশনের আদর্শ/উদ্দেশ্যের প্রতি আস্থাবান বাংলা ডিসিপ্লিন থেকে উত্তীর্ণ স্নাতক/ স্নাতকোত্তর ডিগ্রিধারী গ্র্যাজুয়েটদের সমন্বয়ে উপদেষ্টা পরিষদ গঠিত হবে।

উপদেষ্টা পরিষদের গঠন ও কার্যপরিধি:

(১) উপদেষ্টা পরিষদ ১ জন প্রধান উপদেষ্টার নেতৃত্বে সর্বোচ্চ ০৫ (পাঁচ) সদস্য বিশিষ্ট হবে।

(২) কার্যনির্বাহী পরিষদ উপদেষ্টা পরিষদ গঠন করবে এবং নতুন কার্যনির্বাহী পরিষদ দায়িত্ব গ্রহণের পর উপদেষ্টা পরিষদ বিলুপ্ত হয়ে যাবে।

(৩) সদ্য বিগত কার্যনির্বাহী পরিষদের সভাপতি পদাধিকারবলে পরবর্তী উপদেষ্টা পরিষদের সদস্য হবেন।

(৪) উপদেষ্টা পরিষদ কার্যনির্বাহী পরিষদের সিদ্ধান্তে বা সভাপতির অনুরোধে কোন বিষয়ে পরামর্শ প্রদান করবে।

(৫) সভাপতির আমন্ত্রণে যে কোন উপদেষ্টা পরিষদ সদস্য কার্যনির্বাহী পরিষদ সভায় অংশগ্রহণ করবেন, কার্যকরী ভূমিকা রাখবেন। তবে, সভার কোন প্রস্তাবের উপর বিভক্ত ভোটের ক্ষেত্রে ভোটদানে বিরত থাকবেন।

(৬) উপদেষ্টা পরিষদ সদস্যগণ কোন নির্বাহী দায়িত্ব পালন করবে না। তবে কার্যনির্বাহী পরিষদের দায়িত্ব হস্তান্তর বিষয়ে উপদেষ্টা পরিষদ প্রয়োজনীয় ভূমিকা রাখবেন। অ্যাসোসিয়েশনের সকল বিষয়ে তীক্ষ্ণ দৃষ্টি রাখবেন এবং সভাপতিকে সার্বিকভাবে উপদেশ প্রদান করবেন।

৩.৪ উপ-পরিষদ:

অ্যাসোসিয়েশনের কোন অনুষ্ঠান আয়োজন বা কর্মসূচি/প্রকল্প বাস্তবায়নের জন্য কার্যনির্বাহী পরিষদ যে কোন সময় যে কোন সংখ্যক উপ-পরিষদ গঠন করতে পারবে।

উপ-পরিষদের গঠন ও কার্যপরিধি:

(১) উপ-পরিষদ যে কোন সদস্য সংখ্যক হতে পারবে, তন্মধ্যে ১ জন আহ্বায়ক (প্রয়োজনে এক বা একাধিক যুগ্ম আহ্বায়কসহ) এবং ১ জন সদস্য-সচিব থাকবে।

(২) নির্ধারিত সময়ের মধ্যে উপ-পরিষদ নির্দিষ্ট দায়িত্ব পালন করবে এবং সকল কর্মকাণ্ডের জন্য কার্যনির্বাহী পরিষদের নিকট দায়বদ্ধ থাকবে।

(৩) কার্য সম্পাদনের শেষে উপ-পরিষদ কার্যনির্বাহী পরিষদের সভাপতির নিকট রিপোর্ট দাখিল করবে এবং কার্যনির্বাহী পরিষদের সভায় রিপোর্ট অনুমোদিত হওয়ার পর উপ-পরিষদ বিলুপ্ত হয়ে যাবে। কোনো রূপ কারণ দর্শানো ছাড়াই কার্যনির্বাহী পরিষদ যে কোন উপ-পরিষদ ভেঙে দেয়ার ক্ষমতা সংরক্ষণ করে।

(৪) একই বিশেষ কার্য সম্পাদনের জন্য একাধিক উপ-পরিষদ গঠন করা যাবে না। কিন্তু একই সময় ভিন্ন ভিন্ন কার্য সম্পাদনের জন্য একাধিক উপ-পরিষদ গঠন করা যাবে।

### চতুর্থ অধ্যায়: পরিষদসমূহের সভা

৪.১ সাধারণ সভা:

(১) সাধারণ পরিষদের সভা সাধারণ সভা নামে অভিহিত। অ্যালামনাই অ্যাসোসিয়েশনের সকল সদস্য এ সভার সদস্য। বছরে ২টি সাধারণ সভা অনুষ্ঠিত হবে। কার্যনির্বাহী পরিষদের এক পূর্ণ মেয়াদে অর্থাৎ ২ বছরে কমপক্ষে চারটি সাধারণ সভা হতে হবে।

(২) কার্যনির্বাহী পরিষদের সিদ্ধান্তে সাধারণ সম্পাদক এ সভা আহ্বান করবেন। কমপক্ষে ২০ দিনের নোটিশে সভা আহ্বান করতে হবে। জরুরি অবস্থায় ১০ দিনের নোটিশে এ সভা আহ্বান করা যাবে। সভার অন্তত ৫ দিন পূর্বে সদস্যদের পত্র প্রেরণ করতে হবে।

(৩) মোট সদস্যের এক-তৃতীয়াংশের উপস্থিতিতে সভার কোরাম হবে। সংখ্যাগরিষ্ঠ সদস্যের সমর্থনে/সম্মতিতে/কণ্ঠভোটে সভায় উত্থাপিত যে কোন প্রস্তাব অনুমোদিত/গৃহীত হবে।

(৪) সাধারণ সম্পাদক অ্যাসোসিয়েশনের বার্ষিক/দ্বিবার্ষিক প্রতিবেদন পেশ করবেন। কোষাধ্যক্ষ অ্যাসোসিয়েশনের আর্থিক কর্মকাণ্ডের বিবরণ পেশ করবেন।

৪.২ বিশেষ সাধারণ সভা:

(১) সাধারণ পরিষদের জরুরি/বিশেষ সভা বিশেষ সাধারণ সভা হিসেবে অভিহিত হবে।

(২) অ্যাসোসিয়েশনের জরুরি বা বিশেষ প্রয়োজনে বছরে একাধিক বিশেষ সাধারণ সভা ডাকা যেতে পারে। কার্যনির্বাহী পরিষদ গঠন, পুনর্গঠন ও বাতিলকরণ ব্যতীত সাধারণ সভার সকল সিদ্ধান্ত এ সভায় গ্রহণ করা যাবে।

(৩) বিশেষ সাধারণ সভা কমপক্ষে ১০ (দশ) দিনের নোটিশে আহ্বান করতে হবে। 

৪.৩ কার্যনির্বাহী পরিষদ সভা:

(১) কার্যনির্বাহী পরিষদের সভা অ্যালামনাই অ্যাসোসিয়েশনের কার্যনির্বাহী পরিষদ সদস্যদেরকে নিয়ে সভাপতির অনুরোধে সাধারণ সম্পাদক এ সভা ডাকবেন এবং সভাপতি আলোচ্যসূচি নির্ধারণ করবেন।

(২) প্রতি মাসে অন্তত ১টি সভা অনুষ্ঠিত হতে হবে। সভা অনুষ্ঠানের কমপক্ষে ৭ দিন পূর্বে সাধারণ সম্পাদক এ সভার নোটিশ জারি করবেন। সাধারণ সম্পাদক সভা আহ্বান না করলে যুগ্ম সাধারণ সম্পাদকগণ সভাপতির অনুরোধে এ সভার নোটিশ জারি করতে পারবেন। বিশেষ পরিস্থিতিতে সভাপতি নিজেই এ সভা ডাকতে পারবেন।

(৩) জরুরি প্রয়োজনে ২৪ ঘণ্টার নোটিশেও কার্যনির্বাহী পরিষদ সভা আহ্বান করা যাবে। সেক্ষেত্রে পরিষদের সদস্যদেরকে টেলিফোনে/ইলেকট্রনিক মেইলে অবহিত করতে হবে।

(৪) মোট সদস্যের এক-তৃতীয়াংশ সদস্য উপস্থিত থাকলে সভার কোরাম হবে। সংখ্যাগরিষ্ঠ সদস্যের সমর্থনে/সম্মতিতে/ভোটে সভার প্রস্তাব অনুমোদিত/গৃহীত হবে।

(৫) সাধারণ সম্পাদক সভা পরিচালনা করবেন। সাধারণ সম্পাদকের অনুরোধে যুগ্ম সাধারণ সম্পাদকগণের যে কেউ সভা পরিচালনা করতে পারবেন। তবে সভাপতির অনুমতিপূর্বে যুগ্ম সাধারণ সম্পাদকগণ কিংবা যে কোন বিভাগীয় সম্পাদক সভা পরিচালনা করতে পারবেন।

৪.৪ তলবী সভা:

(১) এক নাগাড়ে ৯ মাস কার্যনির্বাহী পরিষদের সভা না ডাকা হলে অ্যালামনাই অ্যাসোসিয়েশনের এক-চতুর্থাংশ সদস্য যৌথস্বাক্ষরে কার্যনির্বাহী পরিষদের ‘তলবী সভা’ ডাকতে পারবেন।

(২) অ্যাসোসিয়েশনের সদস্যগণের এক-পঞ্চমাংশ সদস্য নির্দিষ্ট আলোচ্যসূচির উপর সাধারণ সভা আহ্বানের জন্য সভাপতিকে লিখিত অনুরোধ জানালে যদি তিনি গ্রহণযোগ্য কোন কারণ ব্যতিরেকে সাধারণ সভা আহ্বান না করেন তাহলে অনুরোধকারীগণ নিজেরাই উক্ত আলোচ্যসূচির উপর তলবী সাধারণ সভা আহ্বান করতে পারবেন।

(৩) কোরাম পূর্ণ হলে তলবী সভায় গঠনতন্ত্রের আলোকে সিদ্ধান্ত গ্রহণ করা যাবে।

৪.৫ মুলতবী সভা:

অ্যাসোসিয়েশনের কোন সভায় কোরাম না হলে সে সভাকে মুলতবী ঘোষণাপূর্বক ৭ দিন পরবর্তী দিবসে একই স্থানে ও সময়ে উক্ত সভা অনুষ্ঠিত হবে। মুলতবী সভায় উপস্থিত সদস্যদেরকে নিয়েই কোরাম হবে। এ সভায় অ্যাসোসিয়েশনের বিলুপ্তি, গঠনতন্ত্র সংশোধন, কার্যনির্বাহী পরিষদ গঠন/পুনর্গঠন/বাতিল প্রভৃতি বিষয়ে সিদ্ধান্তগ্রহণ করা যাবে না।

### পঞ্চম অধ্যায়: কার্যনির্বাহী পরিষদ নির্বাচন

  

৫.১ নির্বাচন কমিশন গঠন:

(১) দৈব দুর্বিপাক ও বিশেষ কোন পরিস্থিতি ব্যতীত কার্যনির্বাহী পরিষদের মেয়াদ শেষ হবার ন্যূনতম ৬০ (ষাট) দিন পূর্বে থেকে পরবর্তী কার্যনির্বাহী পরিষদ নির্বাচন অনুষ্ঠানের লক্ষ্যে কার্যনির্বাহী পরিষদ নির্বাচন কমিশন গঠন করবে।

(২) নির্বাচন কমিশন ১ (এক) জন প্রধান নির্বাচন কমিশনার এবং ২ (দুই) জন কমিশনারের সমন্বয়ে ৩ (তিন) সদস্য বিশিষ্ট হবে। নির্বাচন কমিশনে ন্যূনতম ১ (এক) জন সদস্য খুলনা বিশ্ববিদ্যালয় অ্যালামনাই অ্যাসোসিয়েশন (KUAA)-এর মধ্য থেকে নির্ধারিত হবেন। নির্বাচন কমিশনের সভায় প্রধান নির্বাচন কমিশনার সভাপতিত্ব করবেন। প্রধান নির্বাচন কমিশনারসহ ২ (দুই) জন সদস্যের উপস্থিতিতে সভার কোরাম পূর্ণ হবে।

(৩) কার্যনির্বাহী পরিষদ নির্ধারিত সময়ের মধ্যে পরবর্তী কার্যনির্বাহী পরিষদের নির্বাচন অনুষ্ঠানের উদ্যোগ না নিয়ে কিংবা নির্বাচন অনুষ্ঠানে ব্যর্থ হলে গঠনতন্ত্রের উপ-ধারা ৩.২(১)২ এর আলোকে গঠিত ৩ (তিন) সদস্যের আহ্বায়ক কমিটি নির্বাচন কমিশন গঠন করবে।

৫.২ কার্যনির্বাহী পরিষদ নির্বাচন:

(১) সাধারণ সভায় কার্যনির্বাহী পরিষদ গঠন:

অ্যাসোসিয়েশনের সাধারণ সভায় অ্যালামনাই অ্যাসোসিয়েশনের কার্যনির্বাহী পরিষদ নির্বাচন অনুষ্ঠিত হবে। এ লক্ষ্যে গঠনতন্ত্রের বিধানের আলোকে আহ্বানকৃত সাধারণ সভা দুটি পর্বে বিভক্ত থাকবে:

১. প্রথম পর্ব কার্যনির্বাহী পরিষদের মেয়াদের কর্মকাণ্ডের মূল্যায়ন, আয়-ব্যয়ের হিসাব উত্থাপন, সাধারণ আলোচনা, অনুমোদন ইত্যাদির মধ্যে সীমাবদ্ধ থাকবে।

২. দ্বিতীয় পর্বে কার্যনির্বাহী পরিষদ নির্বাচন অনুষ্ঠিত হবে। সমঝোতার ভিত্তিতে কার্যনির্বাহী পরিষদ গঠনের চেষ্টা করতে হবে। উপস্থিত অ্যাসোসিয়েশনের সদস্যগণের মধ্যে শুধুমাত্র বৈধ ভোটারগণের/সদস্যগণের ঐকমত্যে কিংবা সংখ্যাগরিষ্ঠের মতামত/কণ্ঠভোটের ভিত্তিতে নির্বাচন কমিশন কার্যনির্বাহী পরিষদ নির্বাচন সম্পন্ন করবেন। গঠনতন্ত্রের ধারা ৬.২ এর উপধারাসমূহ অনুযায়ী নিবন্ধিত ও বাৎসরিক চাঁদা পরিশোধকৃত সকল সাধারণ সদস্য এবং সকল জীবন সদস্য বৈধ ভোটার হিসেবে গণ্য হবেন ও নির্বাচন কমিশন কর্তৃক তাদের তালিকা প্রকাশিত হবে। কোন সাধারণ সদস্য এর বাৎসরিক চাঁদা হাল নাগাদ না থাকলে তিনি কার্যনির্বাহী পরিষদের নির্বাচনে অংশ গ্রহণ করতে পারবেন না বা তার নাম ভোটার তালিকায় অন্তর্ভুক্ত করা যাবে না।

৩. সর্বসম্মত প্রস্তাবে/সিদ্ধান্তে/কণ্ঠভোটে নির্বাচিত কার্যনির্বাহী পরিষদ উক্ত সাধারণ সভায় ঘোষণাপূর্বক নোটিশ বোর্ডে টাঙিয়ে দেয়া হবে।

(২) সাধারণ সভায় বৈধ ভোটারদের সমঝোতার ভিত্তিতে কার্যনির্বাহী পরিষদ গঠন করা না গেলে গঠিত নির্বাচন কমিশন ভোটের মাধ্যমে কার্যনির্বাহী পরিষদ নির্বাচন সম্পন্ন করবেন। অ্যাসোসিয়েশনের সকল বৈধ সদস্য অর্থাৎ সকল বৈধ সাধারণ সদস্য এবং জীবন সদস্য এ নির্বাচনে ভোটার হিসেবে ভোটার তালিকায় অন্তর্ভুক্ত হবেন।

৫.৩ কার্যনির্বাহী পরিষদ নির্বাচনী তফসিল ঘোষণা:

সাধারণ সভায় কার্যনির্বাহী পরিষদ নির্বাচন অনুষ্ঠান ঘোষণা হবার ১০ (দশ) দিনের মধ্যে নির্বাচন কমিশন খসড়া ভোটার তালিকা প্রকাশপূর্বক নির্বাচনী তফসিল ঘোষণা করবেন।

নির্বাচনী তফসিলে নিম্নলিখিত বিষয়গুলো উল্লেখ থাকতে হবে:

(১) খসড়া ভোটার তালিকা প্রকাশ

(২) খসড়া ভোটার তালিকার উপর আপত্তি

(৩) চূড়ান্ত ভোটার তালিকা প্রকাশ

(৪) মনোনয়নপত্র সংগ্রহ ও জমা দেয়ার তারিখ ও সময়

(৫) খসড়া প্রার্থীতা তালিকা প্রকাশ

(৬) খসড়া প্রার্থীতা তালিকার উপর আপত্তি গ্রহণ ও শুনানি

(৭) মনোনয়নপত্র প্রত্যাহারের শেষ তারিখ ও সময়

(৮) চূড়ান্ত প্রার্থীতা তালিকা প্রকাশ

(৯) নির্বাচন অনুষ্ঠানের স্থান, তারিখ এবং সময়

৫.৪ কার্যনির্বাহী পরিষদ নির্বাচন বিধানাবলী:

(১) চূড়ান্ত প্রার্থীতা তালিকায় কোন পদের/পদসমূহের জন্য একাধিক প্রার্থী থাকলে কেবলমাত্র সে সকল পদে/পদসমূহে নির্বাচন অনুষ্ঠিত হবে।

(২) সদস্য পদে কখনও প্রার্থী সংখ্যা কম থাকার কারণে নির্বাচন অনুষ্ঠানের প্রয়োজন না হলে প্রার্থীদের খুলনা বিশ্ববিদ্যালয়-এ ভর্তির জ্যেষ্ঠতা অনুযায়ী সদস্যদের ক্রম নির্ধারিত হবে। কোন পদে সমসংখ্যক ভোট হলে নির্বাচন কমিশন লটারির মাধ্যমে সিদ্ধান্ত গ্রহণ করবেন।

(৩) যদি কোন কারণে কোন পদে/পদসমূহে প্রার্থী না থাকে তবে সভাপতি ও সাধারণ সম্পাদকের পদ ছাড়া বাকী পদসমূহ নির্বাচিত কার্যনির্বাহী পরিষদ পরবর্তী সময়ে কো-অপশনের মাধ্যমে পূরণ করবে, তবে এ সংখ্যা কার্যনির্বাহী পরিষদের মোট পদ সংখ্যার এক-তৃতীয়াংশের বেশি হতে পারবে না। সভাপতি ও সাধারণ সম্পাদককে অবশ্যই নির্বাচনী প্রক্রিয়ার মাধ্যমে নির্বাচিত হতে হবে।

(৪) কোন সদস্য পর পর দুই মেয়াদ কার্যনির্বাহী পরিষদের সভাপতি অথবা সাধারণ সম্পাদক পদে অধিষ্ঠিত থাকলে পরবর্তী মেয়াদের জন্য অর্থাৎ পরম্পরায় তৃতীয় মেয়াদের জন্য একই পদে প্রার্থী হতে পারবেন না। তবে এক মেয়াদ বিরতি দিয়ে পরে আবার একই পদে প্রার্থী হতে বাধা থাকবে না।

(৫) কার্যনির্বাহী পরিষদ নির্বাচনে প্রার্থীগণ ৫১ (একান্ন) জনের পূর্ণ প্যানেল কিংবা যে কোন সংখ্যক পদে যুক্তভাবে কিংবা এককভাবে প্রতিদ্বন্দ্বিতা করতে পারবেন। কোন প্রার্থী একাধিক পদে প্রতিদ্বন্দ্বিতা করতে পারবেন না। মনোনয়নপত্র পূর্ণ প্যানেল হিসেবে একসাথে সংগ্রহ করতে হবে, কোন মনোনয়নপত্র এককভাবে সংগ্রহ করা যাবে না।

(৬) নির্বাচন কমিশন কর্তৃক নির্ধারিত মনোনয়ন ফি (অফেরতযোগ্য) নগদ জমা দিয়ে নির্বাচন কমিশনের নিকট থেকে নির্বাচনের মনোনয়নপত্র সংগ্রহ করতে হবে। যে কোন সদস্য চূড়ান্ত ভোটার তালিকার কপি নির্বাচন কমিশন কর্তৃক নির্ধারিত অর্থ পরিশোধপূর্বক সংগ্রহ করতে পারবেন।

(৭) মনোনয়নপত্র দাখিল করতে প্রত্যেক প্রার্থীর জন্য একজন ভোটারের প্রস্তাব এবং অন্য একজন ভোটারের সমর্থন থাকতে হবে।

(৮) মনোনয়নপত্র দাখিলের ৪৮ ঘণ্টার মধ্যে নির্বাচন কমিশন প্রার্থীগণের খসড়া তালিকা প্রকাশ করবেন। খসড়া প্রার্থীতা তালিকা প্রকাশের ৪৮ ঘণ্টার মধ্যে প্রার্থীতার উপর আপত্তি (যদি থাকে) নির্বাচন কমিশনে পেশ করা যাবে। অতঃপর পরবর্তী ৪৮ ঘণ্টার মধ্যে চূড়ান্ত প্রার্থী তালিকা প্রকাশ করা হবে। চূড়ান্ত প্রার্থী তালিকা প্রকাশের ১৫ দিনের মধ্যে নির্বাচন সম্পন্ন করতে হবে।

(৯) যদি কোন কারণে কার্যনির্বাহী পরিষদ নির্বাচন স্থগিত হয়ে যায় কিংবা কার্যনির্বাহী পরিষদের মেয়াদে নির্বাচন করা সম্ভব না হয় তবে মেয়াদ শেষ হবার পর আরও অনধিক ৩ (তিন) মাস কার্যনির্বাহী পরিষদ বহাল থেকে গঠিত নির্বাচন কমিশনের মাধ্যমে কিংবা প্রয়োজনে নতুন নির্বাচন কমিশন গঠনপূর্বক কার্যনির্বাহী পরিষদ নির্বাচন সম্পন্ন করবে।

(১০) উক্ত ৩ (তিন) মাসের মধ্যে নির্বাচন সম্পন্ন না হলে কার্যনির্বাহী পরিষদ আরও ৩ (তিন) মাস বহাল থেকে গঠিত নির্বাচন কমিশনের মাধ্যমে কিংবা প্রয়োজনে নতুন নির্বাচন কমিশন গঠনপূর্বক কার্যনির্বাহী পরিষদ নির্বাচন সম্পন্ন করবে।

(১১) কার্যনির্বাহী পরিষদ উক্ত ৩ (তিন) মাসের মধ্যে নির্বাচন সম্পন্ন করতে ব্যর্থ হলে নতুন কার্যনির্বাহী পরিষদ গঠন/নির্বাচন বিষয়ে গঠনতন্ত্রের ধারা ৩.২(১)৩ মোতাবেক পদক্ষেপ নেয়া যাবে।

(১২) কার্যনির্বাহী পরিষদ নির্বাচন বিধানাবলী কিংবা নির্বাচন সংক্রান্ত অন্য যে কোন বিষয়ে সৃষ্ট অস্পষ্টতা কিংবা বিরোধ কিংবা বিতর্কের উপর নির্বাচন কমিশনের সিদ্ধান্তই চূড়ান্ত বলে বিবেচিত হবে।

### ষষ্ঠ অধ্যায়: অ্যাসোসিয়েশনের আর্থিক ব্যবস্থাপনা

  

৬.১ অ্যাসোসিয়েশনের তহবিল ও আয়ের উৎস:

(১) অ্যাসোসিয়েশনের সদস্য অন্তর্ভূক্তি ফি, অ্যাসোসিয়েশনের নামে সংগৃহীত চাঁদা, অনুদান এবং অন্যান্য অর্থ অ্যাসোসিয়েশনের তহবিল হিসেবে গণ্য হবে।

(২) শিক্ষা, আর্থ-সামাজিক, তথ্য-প্রযুক্তি প্রভৃতি ক্ষেত্রে উন্নয়নধর্মী প্রকল্প/কর্মকান্ডের জন্য অ্যাসোসিয়েশনের নামে সংগৃহীত অর্থ বিশেষ তহবিল বলে গণ্য হবে।

(৩) শর্তহীন ব্যক্তিগত এবং প্রাতিষ্ঠানিক (সরকারি/বেসরকারি) অনুদান।

(৪) শেয়ার, সঞ্চয়ী সার্টিফিকেট, সিকিউরিটিজ বা যে কোন লাভজনক প্রকল্পে অ্যাসোসিয়েশনের তহবিল বিনিয়োগের মাধ্যমে অর্জিত অর্থ।

(৫) অন্যান্য অনুরূপ উৎস থেকে প্রাপ্ত অর্থ/অনুদান।

৬.২ অ্যাসোসিয়েশনের সদস্য নিবন্ধন ফি ও চাঁদা:

(১) সাধারণ সদস্য নিবন্ধন ফি ও চাঁদা:

১. খুলনা বিশ্ববিদ্যালয় অ্যালামনাই অ্যাসোসিয়েশন (KUAA)- এর সাধারণ সদস্যপদের নিবন্ধন ফি এবং বার্ষিক চাঁদার হার কার্যনির্বাহী পরিষদ কর্তৃক নির্ধারিত হবে। কার্যনির্বাহী পরিষদ সময় ও পরিবেশ বিবেচনায় নিয়ে এই চাঁদার হার নির্ধারণ করতে পারবে এবং তা সকল মাধ্যমে (ওয়েব পেজ, ফেসবুক পেজ, বিজ্ঞপ্তি আকারে প্রভৃতি) প্রকাশ করবে এবং ইলেকট্রনিক মেইলের/ডাকযোগে চিঠির মাধ্যমে প্রত্যেক সদস্যকে অবহিত করবে।

২. সাধারণ সদস্যপদের জন্য আবেদনের সময় নিবন্ধন ফি এর সাথে ১ বছরের চাঁদা জমা প্রদান করতে হবে।

৩. স্থানীয়/আন্তর্জাতিক পরিষদের সাধারণ সদস্যগণ সংগঠনের সাধারণ সদস্য হিসেবে বিবেচ্য হবেন। এখানে উল্লেখ্য যে, স্থানীয়/আন্তর্জাতিক পরিষদ কর্তৃক গৃহীত সদস্য ফি এবং চাঁদার এক-তৃতীয়াংশ (১/৩) মূল সংগঠনের অংশ হিসেবে প্রেরিত হবে।

(২) জীবন সদস্য নিবন্ধন ফি:

অ্যাসোসিয়েশনের জীবন সদস্যপদের নিবন্ধন ফি ১০,০০০/- (দশ হাজার) টাকা যা সদস্যপদ গ্রহণ ফি হিসেবে এককালীন গৃহীত হবে। জীবন সদস্যকে সদস্যপদের জন্য আর কোনরূপ বার্ষিক কিংবা মাসিক চাঁদা পরিশোধ করতে হবে না।

৬.৩ অ্যাসোসিয়েশনের কর্মকর্তা/কর্মচারী নিয়োগ:

সভাপতির অনুমোদন সাপেক্ষে সাধারণ সম্পাদক অ্যাসোসিয়েশনের কর্মকর্তা/কর্মচারী নিয়োগ প্রদান করবেন। অ্যাসোসিয়েশনের কর্মকর্তা/কর্মচারীদের নিয়োগ, অব্যাহতি, বেতন-ভাতা, ছুটি ইত্যাদি সার্বিকভাবে কার্যনির্বাহী পরিষদের সিদ্ধান্তে নির্ধারিত এবং নিয়ন্ত্রিত হবে।

৬.৪ অ্যাসোসিয়েশনের সম্পত্তি ও তহবিল ব্যবস্থাপনা:

(১) অ্যাসোসিয়েশনের সকল স্থাবর/অস্থাবর সম্পত্তি, মূলধন, পোর্টফোলিও বিনিয়োগ, তহবিল প্রভৃতির একটি সুষ্ঠু রেকর্ড কোষাধ্যক্ষ সংরক্ষণ করবেন। অ্যাসোসিয়েশনের নামে সংগৃহীত সমুদয় অর্থ অ্যাসোসিয়েশনের নামে করা ব্যাংক হিসাবে জমা রাখবেন।

(২) কোনো সরকারি/বেসরকারি সংস্থা কিংবা কোনো ব্যাংক, বীমা বা অর্থ লগ্নিমনকারী প্রতিষ্ঠান কিংবা কোনো ব্যক্তির নিকট থেকে অ্যাসোসিয়েশন বা অ্যাসোসিয়েশনের পক্ষে কোনো সদস্য কোনো রূপ অর্থ ধার (loan) হিসেবে গ্রহণ করতে পারবে না এবং অ্যাসোসিয়েশনের কোনো অর্থও ধার (loan) হিসেবে প্রদান করা যাবে না।

(৩) কোষাধ্যক্ষ পরবর্তী কার্যনির্বাহী পরিষদের কোষাধ্যক্ষকে সম্পদ/তহবিল বুঝিয়ে দিবেন।

(৪) অ্যাসোসিয়েশনের স্থাবর/অস্থাবর সম্পত্তি কিংবা কোনো তহবিলের ওপর অ্যাসোসিয়েশনের কোনো সদস্যের একক কোনো দাবি থাকবে না।

৬.৫ অ্যাসোসিয়েশনের ব্যাংক হিসাব ও আর্থিক লেনদেন:

(১) সকল সদস্য ফি, চাঁদা, অনুদান কিংবা কোন উৎস, খাত বা ব্যক্তি থেকে আদায়কৃত অর্থ অ্যাসোসিয়েশনের নামে করা ব্যাংক হিসাবে জমা প্রদান করতে হবে।

(২) অ্যাসোসিয়েশনের কার্যনির্বাহী পরিষদ কর্তৃক আয়োজিত কোনো অনুষ্ঠান কিংবা পরিচালিত কোনো কর্মকাণ্ডের আয়-ব্যয়ের চূড়ান্ত হিসাবের উদ্বৃত্ত অর্থ কিংবা ঘাটতি কার্যনির্বাহী পরিষদের অনুমোদনক্রমে অ্যাসোসিয়েশনের তহবিলে সমন্বয় হবে।

(৩) কার্যনির্বাহী পরিষদের সভাপতি, সাধারণ সম্পাদক এবং কোষাধ্যক্ষ এই ৩ (তিন) জনের যৌথ স্বাক্ষরে অ্যাসোসিয়েশনের ব্যাংক হিসাব খোলা/বন্ধ/পরিচালিত হবে।

(৪) কার্যনির্বাহী পরিষদের সভাপতি ও সাধারণ সম্পাদক এ ২ (দুই) জনের যে কোনো ১ (এক) জন এবং কোষাধ্যক্ষের যৌথ স্বাক্ষরে অ্যাসোসিয়েশনের ব্যাংক লেনদেন সম্পন্ন হবে।

৬.৬ অ্যাসোসিয়েশনের হিসাব নিরীক্ষণ:

(১) প্রতি পঞ্জিকা বছরে কিংবা কার্যনির্বাহী পরিষদের পূর্ণ এক মেয়াদে অন্তত একবার অ্যাসোসিয়েশনের আয়-ব্যয়ের হিসাব নিরীক্ষণ করতে হবে।

(২) কার্যনির্বাহী পরিষদ আয়-ব্যয়ের হিসাব সম্পন্নের জন্য অডিটের সম্ভাব্য ব্যয় উল্লেখপূর্বক সাধারণ পরিষদের পূর্ব অনুমোদন গ্রহণ করবে এবং বাংলাদেশে নিবন্ধিত যে কোনো লাইসেন্সধারী অডিটর/অডিট ফার্ম নিয়োগ করবে। নিয়োগকৃত অডিটর/অডিট ফার্ম বাংলাদেশে প্রচলিত সংশ্লিষ্ট আইন ও বিধি-বিধান অনুসারে অডিট সম্পন্ন করবে এবং নির্বাহী পরিষদের নিকট দাখিল করবে। কোষাধ্যক্ষ নির্বাহী পরিষদের পক্ষ থেকে অডিটর/অডিট ফার্মের সাথে সকল ধরনের যোগাযোগ রক্ষা করবেন এবং যে কোনো ধরনের সহযোগিতা ও দিক-নির্দেশনা প্রদান করবেন।

(৩) কার্যনির্বাহী পরিষদের সভায় অনুমোদনের পরেই উক্ত অডিট রিপোর্ট অ্যাসোসিয়েশনের সাধারণ সভায় অনুমোদনের জন্য পেশ করা যাবে।

### সপ্তম অধ্যায়: বিবিধ

  

৭.১ কার্যনির্বাহী পরিষদ সদস্য শূন্যপদ পূরণ:

কার্যনির্বাহী পরিষদের কোন সদস্যের পদত্যাগ, অব্যাহতি, অনাস্থা, সদস্যপদ বাতিল/অপসারণ, মৃত্যু বা অন্য কোন কারণে সদস্যপদ শূন্য হলে কার্যনির্বাহী পরিষদের সভায় অর্ধেক সদস্যের অংশগ্রহণে উপস্থিত সদস্যদের দুই-তৃতীয়াংশ সদস্যের সমর্থনে কো-অপশনের মাধ্যমে উক্ত শূন্য পদ/পদসমূহ পূরণ করা যাবে। তবে শূন্য পদের সংখ্যা মোট পদের ১/৩ অংশের ঊর্ধ্বে হলে তা নির্বাচনের মাধ্যমে পূরণ করতে হবে।

৭.২ কার্যনির্বাহী পরিষদ সদস্যপদ থেকে পদত্যাগ:

(১) কোন কার্যনির্বাহী পরিষদ সদস্য পদত্যাগ করতে চাইলে কারণ উল্লেখপূর্বক তিনি সভাপতি বরাবরে পদত্যাগপত্র পেশ করবেন।

(২) পদত্যাগপত্র পেশের ১৫ দিনের মধ্যে সাধারণ সম্পাদক কার্যনির্বাহী পরিষদের সভা আহ্বান করবেন। উক্ত সভায় পদত্যাগপত্র গৃহীত হলে তিনি অ্যাসোসিয়েশনের সাথে তাঁর সমুদয় হিসাব-নিকাশ সম্পন্ন করা সাপেক্ষে বিমুক্ত হবেন।

(৩) পদত্যাগপত্র কার্যনির্বাহী পরিষদে উত্থাপনের পরে আর তা প্রত্যাহার করা যাবে না, পদত্যাগকারী সদস্য কোন প্রকার বিবৃতি বা পত্র দিতে পারবেন না।

(৪) কার্যনির্বাহী পরিষদের দুই-তৃতীয়াংশ সদস্য পদত্যাগ করলে এটি বাতিল হয়ে যাবে।

৭.৩ কার্যনির্বাহী পরিষদ সদস্যপদ বাতিল/স্থগিতকরণ/অব্যাহতি:

(১) যদি এরূপ প্রতীয়মান হয় যে, কার্যনির্বাহী পরিষদের কোন সদস্য দ্বারা অ্যাসোসিয়েশনের নির্ধারিত দায়িত্ব পালন সম্ভব নয়, সেক্ষেত্রে সাধারণ সম্পাদকের প্রতিবেদনের ভিত্তিতে কার্যনির্বাহী পরিষদের দুই-তৃতীয়াংশ সদস্যের সিদ্ধান্তে উক্ত সদস্যকে তাঁর দায়িত্ব/নির্বাহী পরিষদের সদস্যপদ হতে অব্যাহতি দেয়া যেতে পারে। তবে তাঁর অ্যাসোসিয়েশন সদস্য পদ বহাল থাকবে।

(২) অ্যাসোসিয়েশনের গঠনতন্ত্র বহির্ভূত বা অ্যাসোসিয়েশনের স্বার্থের পরিপন্থী কাজ করলে কার্যনির্বাহী পরিষদ কোন সদস্যের সদস্যপদ সাময়িক স্থগিত করে তাঁর বিরুদ্ধে অভিযোগ গঠনপূর্বক ৩০ (ত্রিশ) দিনের কারণ দর্শানো নোটিশ দিবে। জবাব সন্তোষজনক না হলে কার্যনির্বাহী পরিষদের দুই-তৃতীয়াংশ সদস্যের সিদ্ধান্তে তাঁর সদস্যপদ বাতিল করা যাবে।

(৩) সভাপতির পূর্বানুমতি ব্যতীত কোন কার্যনির্বাহী পরিষদ সদস্য পরপর ৩ (তিন) সভায় অনুপস্থিত থাকলে কার্যনির্বাহী পরিষদের সিদ্ধান্তে তাঁর সদস্যপদ বাতিল করা যাবে।

৭.৪ গঠনতন্ত্র সংশোধন:

(১) সাধারণ পরিষদ সভায় (সাধারণ সভা/বিশেষ সাধারণ সভা) কোরাম অনুযায়ী উপস্থিত সদস্যের দুই-তৃতীয়াংশ সদস্যের সমর্থনে গঠনতন্ত্রের কোন ধারা/অনুচ্ছেদ সংশোধন, সংযোজন বা বিয়োজন করা যাবে।

