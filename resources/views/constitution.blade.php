### প্রথম অধ্যায়: সূচনা

  

১.১ অ্যাসোসিয়েশনের নাম:

এই অ্যাসোসিয়েশনের নাম বাংলা অ্যালামনাই অ্যাসোসিয়েশন (BAAKU) / Bangla Alumni Association (BAAKU)।

১.২ অ্যাসোসিয়েশনের সদস্য:

বাংলা ডিসিপ্লিন থেকে উত্তীর্ণ স্নাতক/ স্নাতকোত্তর ডিগ্রিধারী গ্র্যাজুয়েটগণ এই অ্যাসোসিয়েশনের সদস্য হতে পারবেন। তবে খুলনা বিশ্ববিদ্যালয় থেকে স্নাতক ডিগ্রিধারী নন এরূপ স্নাতকোত্তর ডিগ্রিধারী গ্র্যাজুয়েটগণ অ্যাসোসিয়েশনের কার্যনির্বাহী পরিষদ নির্বাচনে অংশগ্রহণ করতে পারবেন না।

১.৩ অ্যাসোসিয়েশনের ঠিকানা:

খুলনা বিশ্ববিদ্যালয় অ্যালামনাই অ্যাসোসিয়েশন (কুআ) - এর ঠিকানা, কক্ষ নং-০২, পুরাতন প্রশাসনিক ভবন, খুলনা বিশ্ববিদ্যালয় ক্যাম্পাস, খুলনা-৯১০০। অ্যাসোসিয়েশনের বর্তমান অস্থায়ী কার্যালয় হাসান হোল্ডিং (১৩ তলা), ৫২/১, নিউ ইস্কাটন রোড, রমনা, ঢাকা-১০০০। কার্যনির্বাহী পরিষদ প্রয়োজনবোধে ঢাকা মেট্রোপলিটন এলাকার যে কোন স্থানে অ্যাসোসিয়েশনের কার্যালয় স্থানান্তর করতে পারবে। কার্যালয় পরিবর্তনের ১৫ (পনের) দিনের মধ্যে সকল সদস্য এবং সংশ্লিষ্ট কর্তৃপক্ষ/ সংগঠনসমূহকে তা অবহিত করতে হবে।

১.৪ অ্যাসোসিয়েশনের অধিক্ষেত্র:

অ্যাসোসিয়েশনের কার্যক্রম বাংলাদেশের সর্বত্র বিস্তৃত থাকবে। এর সদর দফতর থাকবে খুলনায়। একবার কেউ অ্যাসোসিয়েশনে অন্তর্ভুক্ত হলে ভবিষ্যতে তিনি দেশে-বিদেশে যে কোন স্থানে অবস্থান করুন না কেন তাঁর সদস্যপদের ধারাবাহিকতা বজায় থাকবে।

১.৫ অ্যাসোসিয়েশনের লক্ষ্য ও উদ্দেশ্য:

১. বাংলা ডিসিপ্লিনে অধ্যয়নকারী গ্র্যাজুয়েটদের মধ্যে পারস্পরিক যোগাযোগ, একতা, ভ্রাতৃত্ব, সম্প্রীতি ও সহযোগিতামূলক মনোভাব প্রতিষ্ঠা করা এবং তা বজায় রাখা।

২. অ্যাসোসিয়েশনের সদস্যগণের পেশাগত প্রয়োজনে এবং সুবিধা-অসুবিধায় সংশ্লিষ্ট বিভাগীয় শাখা/কমিটির সাথে সহজতর যোগাযোগে সহায়তা করা।

৩. সদস্যগণের জন্য প্রযুক্তিগত জ্ঞান ও তথ্য অর্জনের সুযোগ সৃষ্টি করা এবং পারস্পরিক জ্ঞান ও তথ্য বিনিময়ে সহায়তা করা।

৪. অ্যাসোসিয়েশনের সদস্যগণের পেশাগত মান উন্নয়নে সহায়তা করা।

৫. বিভিন্ন জনকল্যাণ এবং সমাজসেবা মূলক কাজে অংশগ্রহণ করা।

৬. জাতীয় কোন দুর্যোগে কিংবা জনজীবনে হঠাৎ সৃষ্ট বিপর্যয়কর পরিস্থিতিতে সহায়তামূলক কর্মসূচি নিয়ে এগিয়ে আসা।

১.৬ অ্যাসোসিয়েশনের কার্যক্রম:

১. অ্যাসোসিয়েশন সদস্যগণের মধ্যে পরস্পরি মতামত বিনিময় এবং অন্তরঙ্গ পরিবেশ সৃষ্টির ক্ষেত্র তৈরি করবে।

২. সদস্যগণের একক/যৌথ ন্যায়সংগত সুবিধাদি ও অধিকার বিষয়ে সংশ্লিষ্ট কর্তৃপক্ষের সাথে আলোচনাপূর্বক উপযুক্ত ব্যবস্থা গ্রহণ করবে। প্রয়োজনে সমধর্মী বিভিন্ন অ্যাসোসিয়েশন, প্রতিষ্ঠান, সমিতি, সংস্থা বা ব্যক্তির সাথে যৌথভাবে কাজ করবে।

৩. সদস্যগণের এক/একাধিক সংযোগে পরিচালিত পেশাভিত্তিক উদ্যোগ/কর্মসূচীতে অংশগ্রহণ/সহযোগিতা প্রদান।

৪. অ্যাসোসিয়েশন এককভাবে অথবা অন্যান্য অ্যাসোসিয়েশন/সংস্থার সাথে যৌথভাবে জাতীয় দুর্যোগ প্রতিরোধ, জনবিপর্যয় রোধ, জনকল্যাণ ও সেবামূলক কাজে অংশগ্রহণ করবে।

৫. অ্যাসোসিয়েশনের কর্মকাণ্ড ও সদস্যগণের সৃজনশীল মতামত প্রকাশের জন্য পত্রিকা/বুলেটিন প্রকাশ করবে।

৬. অ্যাসোসিয়েশনের কার্যক্রম পরিচালনার নিমিত্তে আর্থিক সক্ষমতা অর্জনের জন্য অ্যাসোসিয়েশনের সদস্যগণের নিকট থেকে কিংবা সমধর্মী অ্যাসোসিয়েশন/সমিতি/সংস্থা/ ব্যক্তির নিকট থেকে চাঁদা/অনুদান গ্রহণপূর্বক তহবিল গঠন করবে।

### দ্বিতীয় অধ্যায়: অ্যাসোসিয়েশন সদস্য

  

২.১ সদস্য শ্রেণীবিভাগ:

অ্যাসোসিয়েশনের সদস্য হবে ২ (দুই) শ্রেণীর:

- (ক) সাধারণ সদস্য
    
- (খ) জীবন সদস্য
    

(১) সাধারণ সদস্য:

গঠনতন্ত্রের ধারা ১.২ অনুযায়ী অ্যাসোসিয়েশনের সদস্য হওয়ার যোগ্য বাংলা ডিসিপ্লিনের যে কোন গ্র্যাজুয়েটগণ ধারা ৬.২(১) এ নির্ধারিত ফি জমাপূর্বক সদস্য অন্তর্ভুক্তির ফরমে আবেদন করার পর কার্যনির্বাহী পরিষদের অনুমোদনক্রমে তিনি অ্যাসোসিয়েশনের সাধারণ সদস্য হবেন। সদস্য নম্বর সদস্যপদ গ্রহণের তারিখ অনুযায়ী নির্ধারিত হবে।

(২) জীবন সদস্য:

গঠনতন্ত্রের ধারা ১.২ অনুযায়ী অ্যাসোসিয়েশনের সদস্য হওয়ার যোগ্য বাংলা ডিসিপ্লিনের কোন গ্র্যাজুয়েটগণ ধারা ৬.২(২) এ নির্ধারিত ফি প্রদানপূর্বক আবেদন করলে কার্যনির্বাহী পরিষদের অনুমোদনক্রমে তিনি অ্যাসোসিয়েশনের জীবন সদস্য হবেন। জীবন সদস্য নম্বর সদস্যপদ গ্রহণের তারিখের ক্রমানুসারে হবে। কোন জীবন সদস্য ইন্তেকাল করলে ইন্তেকালের তারিখসহ তাঁর নাম ও সদস্য নম্বর থেকে যাবে, কিন্তু ভোটার নম্বর এবং বর্তমান ঠিকানা থাকবে না।

২.২ সদস্যগণের অধিকার:

১. অ্যাসোসিয়েশনের পরিষদসমূহে গঠনতন্ত্রের বিধি-বিধান এবং শর্তাবলী পূরণ সাপেক্ষে নিজেকে অন্তর্ভুক্ত করতে কিংবা পরিষদসমূহের নির্বাচনে অংশগ্রহণ করতে পারবে।

২. অ্যাসোসিয়েশনের কোন সদস্যের ক্ষেত্রে প্রযোজ্য যে কোন সভায় অংশগ্রহণ করার, নিজস্ব মতামত ব্যক্ত করার ও ভোটাধিকার প্রয়োগের অধিকার থাকবে।

৩. অ্যাসোসিয়েশন কর্তৃক আয়োজিত কোন আচার-অনুষ্ঠান এ প্রযোজ্য বিধি-বিধান এবং শর্তাবলীর আলোকে অংশগ্রহণের অধিকার থাকবে।

৪. যে কোন সদস্যের পেশা সংক্রান্ত কিংবা সৃজনশীল কোন কাজে অ্যাসোসিয়েশনের সহযোগিতা চাওয়ার/পাওয়ার অধিকার থাকবে।

২.৩ সদস্যগণের দায়িত্ব:

১. অ্যাসোসিয়েশনের গঠনতন্ত্র মেনে চলা।

২. গোষ্ঠী স্বার্থ ও মর্যাদার প্রতি শ্রদ্ধাশীল হওয়া।

৩. নিজ নিজ পেশার মর্যাদা রক্ষা করা ও উন্নয়নে সচেষ্ট থাকা।

৪. অ্যাসোসিয়েশন কর্তৃক আয়োজিত কোন সভা-সমাবেশ, আচার-অনুষ্ঠান, সেমিনার কিংবা কর্মসূচিতে অংশগ্রহণ করা এবং সেগুলোর বাস্তবায়নে যথাসাধ্য অবদান রাখা।

২.৪ সদস্যপদ বাতিল:

১. গ্রহণযোগ্য কারণ ব্যতিরেকে গঠনতন্ত্রের ধারা ৬.২(১)২ এ বর্ণিত বার্ষিক চাঁদা পরিশোধ না করলে সদস্যপদ সাময়িকভাবে স্থগিত থাকবে। স্থগিত হবার পরবর্তী ১ (এক) বছরের মধ্যে বকেয়া পরিশোধ না করলে স্থগিত সদস্যপদ বাতিল হয়ে যাবে। সদস্যপদ পুনরায় লাভ করতে চাইলে সমুদয় বকেয়া চাঁদাপরিশোধসহ সদস্য নিবন্ধন ফি জমা দিতে হবে।

২. গঠনতন্ত্রের কোন বিধি সুস্পষ্টভাবে লঙ্ঘন করলে কোন সদস্যের বিরুদ্ধে শাস্তিমূলক ব্যবস্থা গ্রহণের পূর্বে অবশ্যই তাঁকে আত্মপক্ষ সমর্থনের সুযোগ দিতে হবে এবং গৃহীত যে কোন শাস্তিমূলক ব্যবস্থা পরবর্তী সাধারণ সভায় অনুমোদিত হতে হবে।

৩. কোন সদস্য সর্বোচ্চ আদালতে দণ্ডিত হলে অথবা তাঁর কর্মকাণ্ড অ্যাসোসিয়েশনের জন্য ক্ষতিকর প্রমাণিত হলে কার্যনির্বাহী পরিষদ তাঁর সদস্যপদ বাতিল করতে পারবে।

৪. কোন সদস্যের মৃত্যু হলে তাঁর সদস্যপদ বিলুপ্ত হবে না, সাবেক সদস্য হিসেবে তাঁর নাম ও সদস্য নম্বর সংরক্ষিত থাকবে। তবে ভোটার তালিকায় তাঁর নাম অন্তর্ভুক্ত হবে না।

২.৫ সদস্যপদ প্রত্যাহার:

যে কোন সদস্য এককভাবে ২ (দুই) মাসের নোটিশে কার্যনির্বাহী পরিষদের সভাপতি বরাবর কারণ উল্লেখপূর্বক সদস্যপদ প্রত্যাহারের আবেদন করতে পারবেন। কার্যনির্বাহী পরিষদের পরবর্তী সভায় তাঁর সদস্যপদ প্রত্যাহার বিষয়ে সিদ্ধান্ত গৃহীত হবে। উক্ত সিদ্ধান্ত আবেদনকারীর মনোপূত না হলে পরবর্তী সাধারণ সভায় তাঁর আবেদন উত্থাপনের জন্য তিনি সভাপতিকে অনুরোধ করতে পারবেন এবং সে ক্ষেত্রে সভাপতি তা পরবর্তী সাধারণ সভায় উত্থাপন করতে বাধ্য থাকবেন। সাধারণ সভার সিদ্ধান্তে বিষয়টি নিষ্পত্তি হবে।

২.৬ সদস্যপদ পুনরুদ্ধার:

১. উপধারা ২.৩(১) মোতাবেক সদস্যপদ স্থগিত হলে প্রযোজ্য সদস্য ফি/বার্ষিক চাঁদা প্রদান সাপেক্ষে সদস্যপদ পুনর্বহাল করা যাবে।

২. গঠনতন্ত্রের ধারা ২.৩(২) ও ২.৩(৩) মোতাবেক কেউ সদস্যপদ হারালে সদস্যপদ পুনর্বহালের জন্য তিনি কার্যনির্বাহী পরিষদের সভাপতির নিকট আবেদন করতে পারবেন।

৩. কার্যনির্বাহী পরিষদের বিবেচনায় যদি তাঁর সদস্যপদ বাতিলের সিদ্ধান্ত বহাল থাকে, তবে সদস্যপদ পুনর্বহালের জন্য সাধারণ সভায় তাঁর আবেদন উত্থাপনের জন্য তিনি সভাপতিকে লিখিতভাবে অনুরোধ করতে পারবেন।

### তৃতীয় অধ্যায়: সাংগঠনিক কাঠামো

  

৩.১ সাধারণ পরিষদ:

১. অ্যাসোসিয়েশনের সকল সদস্য সমন্বয়ে সাধারণ পরিষদ গঠিত।

২. এ পরিষদ অ্যাসোসিয়েশনের যে কোন বিষয়ে সর্বোচ্চ ক্ষমতার অধিকারী।

৩. অ্যাসোসিয়েশনের গঠনতন্ত্র সংশোধন/সংযোজন/পরিবর্ধন, কার্যনির্বাহী পরিষদ গঠন/পুনর্গঠন/বাতিল এবং কার্যনির্বাহী পরিষদের বাজেট ও অডিট রিপোর্ট অনুমোদন ক্ষমতার অধিকারী।

৪. অ্যাসোসিয়েশনের আনুষ্ঠানিক বিলুপ্তি না হওয়া পর্যন্ত সাধারণ পরিষদ কার্যকর থাকবে।

৩.২ কার্যনির্বাহী পরিষদ:

অ্যাসোসিয়েশনের যাবতীয় কার্যক্রম পরিচালনার জন্য অ্যাসোসিয়েশন সদস্যগণের মধ্যে হতে ২৪ (চব্বিশ) সদস্য বিশিষ্ট কার্যনির্বাহী পরিষদ গঠিত হবে। অ্যাসোসিয়েশন পরিচালনায় কার্যনির্বাহী পরিষদ সর্বোচ্চ পরিষদ হিসেবে বিবেচিত হবে। কার্যনির্বাহী পরিষদ সকল কর্মকাণ্ডের জন্য সাধারণ পরিষদের নিকট দায়বদ্ধ থাকবে।

(১) কার্যনির্বাহী পরিষদের মেয়াদ:

১. কার্যনির্বাহী পরিষদের কার্যকাল সাধারণভাব দায়িত্ব গ্রহণের দিন থেকে ২ (দুই) বছর। গ্রহণযোগ্য কারণে এই মেয়াদ অনধিক ৬ মাস কার্যনির্বাহী পরিষদ বৃদ্ধি করতে পারবে।

২. দৈব দুর্বিপাক বা জরুরি পরিস্থিতির কারণে নির্ধারিত সময়ে নির্বাচন করা সম্ভব না হলে বিদ্যমান কার্যনির্বাহী পরিষদ উক্ত পরিস্থিতিতে অ্যাসোসিয়েশনের কর্মকাণ্ড চালিয়ে যাবে।

৩. দায়িত্ব গ্রহণের পর থেকে ২ বছর ৬ মাসের মধ্যে পরবর্তী নির্বাচন অনুষ্ঠানে কার্যনির্বাহী পরিষদ ব্যর্থ হলে অ্যাসোসিয়েশন সদস্যের যে কোন ২০০ জন স্বাক্ষরিত এক/একাধিক দল (একই সদস্য একাধিক দলে স্বাক্ষর করতে পারবেন না) জরুরি সাধারণ সভা আহ্বানের জন্য সভাপতিকে লিখিত অনুরোধ করতে পারবেন। ১ম দলের অনুরোধপত্র প্রাপ্তির ১ মাসের মধ্যে জরুরি সাধারণ সভা অনুষ্ঠানে সভাপতি ব্যর্থ হলে ১ম দল "তলবী সভা" আহ্বান করতে পারবেন (১ম দল ব্যতীত অন্য কোন দল এ সভা আহ্বান করতে পারবে না)। উক্ত তলবী সভায় অ্যাসোসিয়েশন সদস্যগণের সমন্বয়ে ২১ (একুশ) সদস্য বিশিষ্ট আহ্বায়ক কমিটি গঠন করা যাবে। আহ্বায়ক কমিটি ঐ সভাতেই গঠনতন্ত্রের ধারা ৫.১(৩) এর আলোকে নির্বাচন কমিশন গঠনপূর্বক কার্যনির্বাহী পরিষদ গঠনের উদ্যোগ গ্রহণ করবে। এ আহ্বায়ক কমিটি গঠিত হবার সাথে সাথে কার্যনির্বাহী পরিষদ বিলুপ্ত হয়ে যাবে। ১ম দল ব্যর্থ হলে, গঠিত ২য় দল একই উদ্দেশ্য নিয়ে বর্ণিত প্রক্রিয়া অনুসরন করতে পারবে।

(২) কার্যনির্বাহী পরিষদের দায়িত্ব ও কর্তব্য:

১. গঠনতন্ত্রের আওতায় অ্যাসোসিয়েশন পরিচালনার স্বার্থে খুঁটিনাটি বিষয়ে জরুরি বিধি-বিধান প্রণয়ন করতে পারবে যা পরবর্তী সাধারণ সভায় অনুমোদনের জন্য পেশ করতে হবে।

২. অ্যাসোসিয়েশনের আদর্শ, উদ্দেশ্য ও প্রতিশ্রুতি বাস্তবায়নে কার্যক্রম গ্রহণ করবে। নির্ধারিত সময়ে সাধারণ সভা এবং কার্যনির্বাহী পরিষদ নির্বাচনের ব্যবস্থা গ্রহণ করবে।

৩. অসদাচরণ বা গঠনতন্ত্র বিরোধী কর্মকাণ্ডের জন্য বিধান মোতাবেক যে কোন সদস্যের সদস্যপদ বাতিল বা স্থগিত করতে পারবে, তবে এরূপ সিদ্ধান্ত গ্রহণের পূর্বে সংশ্লিষ্ট সদস্যকে আত্মপক্ষ সমর্থনের সুযোগ দিতে হবে।

৪. কোন নির্দিষ্ট কার্যক্রম/কর্মসূচি/অনুষ্ঠান বাস্তবায়নের জন্য নির্দিষ্ট মেয়াদের জন্য উপ-পরিষদ গঠন করতে পারবে।

